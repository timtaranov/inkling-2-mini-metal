#!/usr/bin/env python3
"""Extract the codebooks of the GGUF "IQ" weight formats from a llama.cpp checkout into src/quant_tables.h.
These tables are part of the file format definition (ggml/src/ggml-common.h, MIT licence); nothing else
of ggml is used.   usage: tools/gen_quant_tables.py ../llama.cpp src/quant_tables.h src/quant_tables.metal"""
import re, sys
src = open(sys.argv[1] + "/ggml/src/ggml-common.h").read()
want = {"ksigns_iq2xs": "uint8_t", "iq2xxs_grid": "uint64_t", "iq2xs_grid": "uint64_t", "iq2s_grid": "uint64_t",
        "iq3xxs_grid": "uint32_t", "iq1s_grid": "uint64_t", "kvalues_iq4nl": "int8_t"}
out = ["// generated by tools/gen_quant_tables.py from ggml-common.h (GGUF weight-format codebooks) - do not edit",
       "#pragma once", "#include <cstdint>", "namespace qt {"]
for name, ty in want.items():
    m = re.search(r"GGML_TABLE_BEGIN\(\s*%s\s*,\s*%s\s*,\s*(\w+)\s*\)(.*?)GGML_TABLE_END\(\)" % (ty, name), src, re.S)
    if not m: sys.exit("table %s not found" % name)
    vals = [v for v in re.sub(r"//.*", "", m.group(2)).replace("\n", " ").split(",") if v.strip()]
    out.append("static const %s %s[%d] = {" % (ty, name, len(vals)))
    for i in range(0, len(vals), 8):
        out.append("    " + ", ".join(v.strip() for v in vals[i:i + 8]) + ",")
    out.append("};")
out.append("}  // namespace qt")
open(sys.argv[2], "w").write("\n".join(out) + "\n")

# the same codebooks for the Metal kernels that read these formats in place (8 bytes per entry as uint2)
if len(sys.argv) > 3:
    m = ["// generated by tools/gen_quant_tables.py from ggml-common.h (GGUF weight-format codebooks) - do not edit"]
    def table(name):
        mm = re.search(r"GGML_TABLE_BEGIN\(\s*\w+\s*,\s*%s\s*,\s*(\w+)\s*\)(.*?)GGML_TABLE_END\(\)" % name, src, re.S)
        return [int(v.strip(), 0) for v in re.sub(r"//.*", "", mm.group(2)).replace("\n", " ").split(",") if v.strip()]
    for name, mname in (("iq2xxs_grid", "kIQ2XXS"), ("iq2xs_grid", "kIQ2XS"), ("iq2s_grid", "kIQ2S"), ("iq1s_grid", "kIQ1S")):
        vals = table(name)
        m.append("constant uint2 %s[%d] = {" % (mname, len(vals)))
        for i in range(0, len(vals), 4):
            m.append("    " + ", ".join("uint2(0x%08xu, 0x%08xu)" % (v & 0xffffffff, v >> 32) for v in vals[i:i + 4]) + ",")
        m.append("};")
    vals = table("ksigns_iq2xs")
    m.append("constant uchar kSigns[%d] = {" % len(vals))
    for i in range(0, len(vals), 16):
        m.append("    " + ", ".join(str(v) for v in vals[i:i + 16]) + ",")
    m.append("};")
    # UE4M3 block scales of NVFP4 (halved, as the E2M1 values are stored doubled)
    def ue4m3(x):
        if x == 0 or x == 0x7f: return 0.0
        e, mm = (x >> 3) & 15, x & 7
        return (mm * 2.0 ** -9 if e == 0 else (1 + mm / 8) * 2.0 ** (e - 7)) * 0.5
    m.append("constant float kUE4M3[256] = {")
    for i in range(0, 256, 8):
        m.append("    " + ", ".join(repr(float(ue4m3(v))) for v in range(i, i + 8)) + ",")
    m.append("};")
    open(sys.argv[3], "w").write("\n".join(m) + "\n")
