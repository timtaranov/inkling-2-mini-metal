#!/usr/bin/env python3
"""Generate src/unicode_tables.h for the Inkling tokenizer.

The pre-tokenizer only needs a coarse class per code point >= 0x80:
    0 = other (punctuation, symbol, control, unassigned, ...)
    1 = letter       (\\p{L})
    2 = mark         (\\p{M})
    3 = number       (\\p{N})
    4 = whitespace   (\\s)

To stay bit-identical with the reference tokenizer the classes are derived from the reference's
own table (llama.cpp src/unicode-data.cpp) when it is available; otherwise Python's unicodedata is
used (which may be a different Unicode version).  The generated header is self-contained.

usage: gen_unicode.py [path/to/unicode-data.cpp] > src/unicode_tables.h
"""
import os
import re
import sys
import unicodedata

MAX_CPT = 0x110000
WHITESPACE = [0x09, 0x0A, 0x0B, 0x0C, 0x0D, 0x20, 0x85, 0xA0, 0x1680, 0x2000, 0x2001, 0x2002, 0x2003,
              0x2004, 0x2005, 0x2006, 0x2007, 0x2008, 0x2009, 0x200A, 0x2028, 0x2029, 0x202F, 0x205F, 0x3000]

OTHER, LETTER, MARK, NUMBER, SPACE = 0, 1, 2, 3, 4


def from_reference(path):
    src = open(path, encoding="utf-8").read()
    body = src.split("unicode_ranges_flags = {", 1)[1].split("};", 1)[0]
    ranges = [(int(a, 16), int(b, 16)) for a, b in re.findall(r"\{0x([0-9A-Fa-f]+), 0x([0-9A-Fa-f]+)\}", body)]
    assert ranges[0][0] == 0 and ranges[-1][0] == MAX_CPT
    ws_body = src.split("unicode_set_whitespace = {", 1)[1].split("};", 1)[0]
    ws = [int(x, 16) for x in re.findall(r"0x([0-9A-Fa-f]+)", ws_body)]
    flag_class = {0x0002: NUMBER, 0x0004: LETTER, 0x0010: MARK}
    cls = bytearray(MAX_CPT)
    for (start, flags), (end, _) in zip(ranges, ranges[1:]):
        c = flag_class.get(flags & 0xFF, OTHER)
        for cp in range(start, end):
            cls[cp] = c
    for cp in ws:
        cls[cp] = SPACE
    return cls, "llama.cpp unicode-data.cpp"


def from_python():
    cls = bytearray(MAX_CPT)
    m = {"L": LETTER, "M": MARK, "N": NUMBER}
    for cp in range(MAX_CPT):
        cls[cp] = m.get(unicodedata.category(chr(cp))[0], OTHER)
    for cp in WHITESPACE:
        cls[cp] = SPACE
    return cls, "python unicodedata " + unicodedata.unidata_version


def main():
    ref = sys.argv[1] if len(sys.argv) > 1 else None
    if ref and os.path.exists(ref):
        cls, source = from_reference(ref)
    else:
        cls, source = from_python()

    runs = []
    cp = 0x80
    while cp < MAX_CPT:
        end = cp
        while end < MAX_CPT and cls[end] == cls[cp]:
            end += 1
        runs.append((cp, cls[cp]))
        cp = end

    out = []
    out.append("// Generated by tools/gen_unicode.py from %s -- do not edit." % source)
    out.append("// Coarse Unicode classes for code points >= 0x80, as runs: {first code point, class}.")
    out.append("// class: 0 other, 1 letter (L), 2 mark (M), 3 number (N), 4 whitespace.  Last run ends at 0x10FFFF.")
    out.append("#pragma once")
    out.append("#include <cstdint>")
    out.append("")
    out.append("namespace ink {")
    out.append("")
    out.append("struct UniRun { uint32_t first; uint8_t cls; };")
    out.append("")
    out.append("static const UniRun kUniRuns[] = {")
    line = "   "
    for first, c in runs:
        item = " {0x%X,%d}," % (first, c)
        if len(line) + len(item) > 118:
            out.append(line)
            line = "   "
        line += item
    out.append(line)
    out.append("};")
    out.append("static const unsigned kUniRunCount = %d;" % len(runs))
    out.append("")
    out.append("}  // namespace ink")
    sys.stdout.write("\n".join(out) + "\n")


if __name__ == "__main__":
    main()
